import {readFileSync,writeFileSync,mkdirSync} from 'node:fs';
import {fileURLToPath} from 'node:url';
import {dirname} from 'node:path';
import {createHash} from 'node:crypto';
import {roomMessageSchema,messagePolicies,ROOM_LIMITS} from '../packages/protocol/room-contract.mjs';
import {canonicalJson} from '../packages/protocol/schema-validation.mjs';

const schema=roomMessageSchema,defs=schema.$defs,names=Object.keys(messagePolicies);
const pascal=name=>name[0].toUpperCase()+name.slice(1);
const identities={actionId:'ActionId',requestId:'RequestId',gameId:'GameId',roundId:'RoundId',roomId:'RoomId',playerId:'PlayerId',you:'PlayerId',hostId:'PlayerId',judgeId:'PlayerId',readerId:'PlayerId',targetPlayerId:'PlayerId',playerIds:'PlayerId',frozenRoster:'PlayerId',pendingRoster:'PlayerId',order:'PlayerId',ownOrder:'PlayerId',judgeOrder:'PlayerId',bindings:'PlayerId',eventId:'EventId',importId:'ImportId',transferId:'TransferId',cursor:'HistoryCursor'};
const identityTypes=[...new Set(Object.values(identities))];
const className=name=>pascal(name)+(names.includes(name)?'Message':'');
const refName=s=>s.$ref?.slice(8);
const nullable=s=>s.oneOf?.some(b=>b.const===null);
const nonNull=s=>s.oneOf?.find(b=>b.const!==null)||s;
function ts(s,key='') {
  if(s.oneOf)return s.oneOf.map(b=>ts(b,key)).join(' | ');
  if('const'in s)return JSON.stringify(s.const);
  if(s.enum)return s.enum.map(value=>JSON.stringify(value)).join(' | ');
  if(s.$ref)return refName(s)==='id'&&identities[key]?identities[key]:className(refName(s));
  if(s.type==='string')return 'string';
  if(s.type==='integer')return 'number';
  if(s.type==='boolean')return 'boolean';
  if(s.type==='array')return `ReadonlyArray<${ts(s.items,key)}>`;
  if(s.type==='object') {
    if(s.additionalProperties&&typeof s.additionalProperties==='object')return `Readonly<Record<string, ${ts(s.additionalProperties,key||'bindings')}>>`;
    return '{ '+Object.entries(s.properties??{}).map(([field,child])=>`readonly ${field}${s.required?.includes(field)?'':'?'}: ${ts(child,field)}`).join('; ')+' }';
  }
  throw new Error('Unsupported generated TS type');
}
function dart(s,key='') {
  if(nullable(s))return dart(nonNull(s),key).replace(/\?$/,'')+'?';
  if(s.$ref) {
    const name=refName(s),target=defs[name];
    return target.type==='object'?className(name):name==='id'&&identities[key]?identities[key]:dart(target,key);
  }
  if('const'in s)return typeof s.const==='boolean'?'bool':typeof s.const==='number'?'int':'String';
  if(s.enum)return 'String';
  if(s.type==='string')return 'String';
  if(s.type==='integer')return 'int';
  if(s.type==='boolean')return 'bool';
  if(s.type==='array')return `List<${dart(s.items,key)}>`;
  if(s.type==='object'&&Object.values(s.properties??{}).every(child=>child.enum?.every(value=>typeof value==='string')))return 'Map<String, String>';
  throw new Error('Unsupported generated Dart type: '+JSON.stringify(s));
}
function readDart(s,raw,key='') {
  if(nullable(s))return `${raw} == null ? null : ${readDart(nonNull(s),raw,key)}`;
  if(s.$ref) {
    const name=refName(s),target=defs[name];
    if(target.type==='object')return `${className(name)}._(${raw} as Map<String, Object?>)`;
    if(name==='id'&&identities[key])return `${identities[key]}(${raw} as String)`;
    return readDart(target,raw,key);
  }
  if(s.type==='array')return `List<${dart(s.items,key)}>.unmodifiable((${raw} as List).map((value) => ${readDart(s.items,'value',key)}))`;
  if(s.type==='object')return `Map<String, String>.unmodifiable((${raw} as Map<String, Object?>).map((key, value) => MapEntry(key, value as String)))`;
  return `${raw} as ${dart(s,key)}`;
}

const manifest=JSON.parse(readFileSync(new URL('../apps/client/assets/catalogs/manifest.json',import.meta.url),'utf8'));
const metadata={avatarVersion:defs.avatar.properties.version.const,catalogHash:createHash('sha256').update(canonicalJson(manifest)).digest('hex'),questionIds:manifest.catalogs.find(c=>c.kind==='questions').ids,ruleIds:manifest.catalogs.find(c=>c.kind==='rules').ids,limits:ROOM_LIMITS};
let tsOutput='// Generated by scripts/generate-room-dtos.mjs. Do not edit.\n';
tsOutput+='declare const identifierBrand: unique symbol;\n';
for(const name of identityTypes)tsOutput+=`export type ${name} = string & { readonly [identifierBrand]: '${name}' };\n`;
for(const [name,value] of Object.entries(defs))tsOutput+=`export type ${className(name)} = ${ts(value,name==='binding'?'bindings':'')};\n`;
tsOutput+='export type RoomMessage = '+names.map(className).join(' | ')+';\n';
tsOutput+='export const protocolMetadata = '+JSON.stringify(metadata)+' as const;\n';

let dartOutput="// Generated by scripts/generate-room-dtos.mjs. Do not edit.\n// dart format off\npart of 'room_message.dart';\n";
dartOutput+=`const currentProtocolCatalogHash = '${metadata.catalogHash}';\nconst _currentCatalogHash = currentProtocolCatalogHash;\nconst currentAvatarVersion = ${metadata.avatarVersion};\n`;
dartOutput+=`final Map<String, dynamic> _roomSchema = jsonDecode(r'''${JSON.stringify(schema)}''') as Map<String, dynamic>;\n`;
dartOutput+=`final Map<String, dynamic> _protocolMetadata = jsonDecode(r'''${JSON.stringify(metadata)}''') as Map<String, dynamic>;\n`;
for(const [name,value] of Object.entries(defs).filter(([,s])=>s.type==='object')) {
  const klass=className(name),message=names.includes(name);
  dartOutput+=`final class ${klass} extends ${message?'RoomMessage':'JsonDto'} {\n  ${klass}._(super.json) : super._();\n`;
  dartOutput+=`  factory ${klass}.fromJson(Map<String, Object?> json) {\n`;
  if(message)dartOutput+=`    final result = decodeRoomMessage(_dtoWire(json)${['snapshot','delta'].includes(name)?', logical: true':''});\n    if (result is! ${klass}) throw const ProtocolDecodeException('INVALID_MESSAGE');\n    return result;\n`;
  else dartOutput+=`    return ${klass}._(_validateDto('${name}', json));\n`;
  dartOutput+='  }\n';
  if(message) {
    const fields=Object.entries(value.properties).filter(([key])=>!['type','protocolVersion'].includes(key));
    dartOutput+=`  factory ${klass}.create({${fields.map(([key,child])=>`${value.required.includes(key)?'required ':''}${dart(child,key).replace(/\?$/,'')}${!value.required.includes(key)||nullable(child)?'?':''} ${key}`).join(', ')}}) => ${klass}.fromJson({\n    'type': '${name}', 'protocolVersion': 1,\n`;
    for(const [key] of fields)dartOutput+=`    ${value.required.includes(key)?'':`if (${key} != null) `}'${key}': _wireValue(${key}),\n`;
    dartOutput+='  });\n';
  }
  if(value.additionalProperties&&typeof value.additionalProperties==='object') {
    const s=value.additionalProperties;
    dartOutput+=`  Map<String, ${dart(s,'bindings')}> get values => Map.unmodifiable(_json.map((key, value) => MapEntry(key, ${readDart(s,'value','bindings')})));\n`;
  } else {
    for(const [key,child] of Object.entries(value.properties??{})) {
      const optional=!value.required?.includes(key),raw=`_json['${key}']`;
      const type=dart(child,key).replace(/\?$/,'')+((optional||nullable(child))?'?':'');
      const expression=optional&&!nullable(child)?`${raw} == null ? null : ${readDart(child,raw,key)}`:readDart(child,raw,key);
      const override=message&&['type','protocolVersion'].includes(key)?'  @override\n':'';
      dartOutput+=`${override}  ${type} get ${key} => ${expression};\n`;
    }
  }
  dartOutput+='}\n';
}
dartOutput+='RoomMessage _messageFromValidated(Map<String, Object?> json) => switch (json[\'type\']) {\n'+names.map(name=>`  '${name}' => ${className(name)}._(json),`).join('\n')+"\n  _ => throw const ProtocolDecodeException('INVALID_MESSAGE'),\n};\n";

for(const [path,content] of [['../apps/server/src/protocol/room_message.generated.ts',tsOutput],['../apps/client/lib/data/protocol/room_message.g.dart',dartOutput]]) {
  const url=new URL(path,import.meta.url);
  if(process.argv.includes('--check')) {if(readFileSync(url,'utf8').replaceAll('\r\n','\n')!==content)throw new Error('Stale generated DTO: '+url.pathname);}
  else {mkdirSync(dirname(fileURLToPath(url)),{recursive:true});writeFileSync(url,content);}
}
process.stdout.write(`Room DTOs: ${names.length} message types and catalog metadata OK\n`);
